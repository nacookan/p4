import { el } from '../util/dom.js';

function section(title, paragraphs) {
  return el('div', { className: 'card' }, [
    el('h2', { text: title }),
    ...paragraphs.map((p) => (typeof p === 'string' ? el('p', { text: p }) : p)),
  ]);
}

