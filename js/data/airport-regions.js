export function regionOf(airportName) {
  return AIRPORT_TO_REGION[airportName] || 'その他';
}

/**
 * 空港名の配列を、北から南への地方区分ごとにグループ化する。
 * @param {string[]} airports
 * @returns {{region:string, airports:string[]}[]} 空のグループは含まない
 */
export function groupAirportsByRegion(airports) {
  const byRegion = new Map();
  for (const a of airports) {
    const r = regionOf(a);
    if (!byRegion.has(r)) byRegion.set(r, []);
    byRegion.get(r).push(a);
  }
  return REGIONS_NORTH_TO_SOUTH.filter((r) => byRegion.has(r)).map((r) => ({ region: r, airports: byRegion.get(r) }));
}
