// PDF時刻表のエディション（フォント）によっては、一部の漢字が
// 通常のCJK統合漢字ではなく、見た目がほぼ同じ「康熙部首(Kangxi Radicals)」
// 及び「CJK部首補助(CJK Radicals Supplement)」ブロックの文字として
// 埋め込まれており、さらにその文字だけが前後から分離した別トークンとして
// 抽出される（例: "東京（羽田）" が "東京（" "⽻"(U+2F7B) "⽥"(U+2F65) "）" の
// 4トークンに分かれる）。
//
// 2026/07/01〜2026/10/24版PDF（2026-08-02取得）の全70ページを走査し、
// 実際に出現した23種類の文字を、前後の文脈（"⼤阪"→大阪、"⽻⽥"→羽田 等）
// から特定・検証したうえで正規化する。2026/03/29〜2026/06/30版PDFでは
// この問題は発生していなかった（フォントによる差異と考えられる）ため、
// 該当しないPDFに対しては何もしない安全な変換である。
const RADICAL_TO_STANDARD = {
  '⽉': '月', // ⽉ -> 月
  '⽇': '日', // ⽇ -> 日
  '⼊': '入', // ⼊ -> 入
  '⽻': '羽', // ⽻ -> 羽
  '⽥': '田', // ⽥ -> 田
  '⼤': '大', // ⼤ -> 大
  '⻄': '西', // ⻄ -> 西
  '⼾': '戸', // ⼾ -> 戸
  '⼥': '女', // ⼥ -> 女
  '⼭': '山', // ⼭ -> 山
  '⼩': '小', // ⼩ -> 小
  '⼋': '八', // ⼋ -> 八
  '⼝': '口', // ⼝ -> 口
  '⿃': '鳥', // ⿃ -> 鳥
  '⽶': '米', // ⽶ -> 米
  '⼦': '子', // ⼦ -> 子
  '⽯': '石', // ⽯ -> 石
  '⾒': '見', // ⾒ -> 見
  '⾼': '高', // ⾼ -> 高
  '⻑': '長', // ⻑ -> 長
  '⿅': '鹿', // ⿅ -> 鹿
  '⻘': '青', // ⻘ -> 青
  '⾺': '馬', // ⾺ -> 馬
};

/**
 * 康熙部首/CJK部首補助ブロックの文字を、通常のCJK統合漢字に正規化する。
 * 該当しない文字列はそのまま返す（他エディションのPDFには影響しない）。
 */
export function normalizeRadicals(str) {
  let out = str;
  for (const [radical, standard] of Object.entries(RADICAL_TO_STANDARD)) {
    if (out.includes(radical)) out = out.split(radical).join(standard);
  }
  return out;
}

// 地名等の断片トークンとして結合してよい文字クラス:
// CJK統合漢字・ひらがな・カタカナ（ー・ヶを含む）・全角括弧のみ。
// 句読点(。、)・数字・英字は含まない（備考の日付リストや便名・運航会社と
// 誤って結合しないようにするため）。
const NAME_FRAGMENT_RE = /^[一-鿿぀-ゟ゠-ヿ（）]+$/;

// 表の構造や定型文を示す固定語。文字クラス上は結合対象に見えても、
// 地名の一部として隣接トークンに結合してはならない語。
// 「航空券の予約・購入はこちら」「空席照会よりご確認ください」は、
// stripBoilerplateが定型注意書きの終端／内部の目印として厳密一致で
// 検出するため、直後の地名トークン等と結合させてはならない
// （元のPDFでは空白トークンで区切られているが、空白のみのアイテムは
// 抽出時に取り除かれるため、文字クラスだけでは区切りを判別できない）。
const RESERVED_TOKENS = new Set([
  '便名', '出発', '到着', '運航社', '備考', '発着', '国内線時刻表', '現在）',
  '航空券の予約・購入はこちら', '空席照会よりご確認ください',
]);

function isMergeableFragment(tok) {
  return NAME_FRAGMENT_RE.test(tok) && !RESERVED_TOKENS.has(tok);
}

/**
 * PDFの文字送り単位によって分割された地名トークン（例: "東京（", "羽", "田", "）"）を、
 * 隣接する断片同士で結合し、1つの空港名/都市名トークンに復元する。
 * 便名・時刻・運航会社・備考（数字や句読点を含む）は結合対象の文字クラスに
 * 含まれないため、意図せず結合されることはない。
 */
export function mergeNameFragments(tokens) {
  const out = [];
  for (const tok of tokens) {
    if (isMergeableFragment(tok) && out.length > 0 && isMergeableFragment(out[out.length - 1])) {
      out[out.length - 1] += tok;
    } else {
      out.push(tok);
    }
  }
  return out;
}
